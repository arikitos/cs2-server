const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1100}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:8090');
  await page.locator('[name="setup_token"]').fill('browser-test-setup-token');
  await page.locator('#auth-form [name="username"]').fill('arik');
  await page.locator('#auth-form [name="password"]').fill('browser-private-password');
  await page.locator('#auth-submit').click();
  await page.locator('#dashboard').waitFor({state:'visible'});
  await page.locator('#public-address').waitFor();
  await page.waitForFunction(()=>document.querySelector('#public-address').value==='8.8.8.8:27015');
  assert.equal(await page.locator('#public-address').getAttribute('readonly'),'');
  assert.equal(await page.locator('[name="port"]').count(),0);
  assert.equal(await page.locator('[name="network_mode"]').count(),0);
  assert.equal(await page.locator('#dashboard').getByText('optional',{exact:true}).count(),0);
  assert.equal(await page.locator('.mode-option').count(),3);
  await page.waitForFunction(()=>document.querySelector('#players-body').textContent.includes('Demo <player>'));
  const player=page.locator('#players-body tr').first();
  await player.getByRole('button',{name:'Admin',exact:true}).click();
  await page.locator('#confirm-action').click();
  await page.getByRole('button',{name:'Users & bans'}).click();
  await page.waitForFunction(()=>document.querySelector('#users-body').textContent.includes('Game admin'));
  await page.locator('#users-body').getByRole('button',{name:'Ban',exact:true}).click();
  await page.locator('#confirm-action').click();
  await page.waitForFunction(()=>document.querySelector('#users-body').textContent.includes('Banned'));
  await page.locator('#users-body').getByRole('button',{name:'Unban',exact:true}).click();
  await page.locator('#confirm-action').click();
  await page.waitForFunction(()=>document.querySelector('#users-body').textContent.includes('Game admin'));
  await page.getByRole('button',{name:'Dashboard',exact:false}).click();
  await page.locator('#server-form [name="server_name"]').fill('Draft name remains');
  await page.waitForTimeout(3000);
  assert.equal(await page.locator('#server-form [name="server_name"]').inputValue(),'Draft name remains');
  await page.locator('#server-form [name="join_password"]').fill('');
  assert.equal(await page.locator('#server-form [name="join_password"]').inputValue(),'');
  const screenshotDir=process.env.CS2_SCREENSHOT_DIR || '/tmp/cs2-ui-screenshots';fs.mkdirSync(screenshotDir,{recursive:true});
  await page.screenshot({path:screenshotDir+'/dashboard-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:screenshotDir+'/dashboard-mobile.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false,'Mobile page must not overflow horizontally');
  const fresh = await browser.newPage({viewport:{width:1440,height:1100}});
  fresh.on('pageerror',error=>errors.push(error.message));
  await fresh.goto('http://127.0.0.1:8091');
  await fresh.getByRole('heading',{name:'Step 1: Create your panel account'}).waitFor();
  await fresh.locator('[name="setup_token"]').fill('browser-test-setup-token');
  await fresh.locator('#auth-form [name="username"]').fill('first-owner');
  await fresh.locator('#auth-form [name="password"]').fill('first-panel-password');
  await fresh.locator('#auth-submit').click();
  await fresh.locator('#logout').waitFor({state:'visible'});
  await fresh.getByRole('button',{name:'Dashboard',exact:false}).click();
  await fresh.locator('#dashboard').waitFor({state:'visible'});
  await fresh.locator('#credentials-card').waitFor({state:'visible'});
  assert.equal(await fresh.locator('#server-form [name="gslt"]').getAttribute('required'),'');
  assert.match(await fresh.locator('#settings-copy').textContent(),/Step 2/);
  const requestContext = fresh.context().request;
  const session = await (await requestContext.get('http://127.0.0.1:8091/api/session')).json();
  const missingToken = await requestContext.post('http://127.0.0.1:8091/api/install',{data:{},headers:{'X-CSRF-Token':session.csrf}});
  assert.equal(missingToken.status(),400,'First installation requires a Steam server token');
  await fresh.locator('#server-form [name="server_name"]').fill('Fresh CS2');
  await fresh.locator('#server-form [name="gslt"]').fill('c'.repeat(32));
  await fresh.locator('#save-server').click();
  await fresh.waitForFunction(()=>document.querySelector('#badge').textContent==='ready');
  const firstInstall = await (await requestContext.get('http://127.0.0.1:8091/api/status')).json();
  assert.equal(firstInstall.job.verification.build,'12345');
  assert.match(firstInstall.logs.join('\n'),/No server installation found/);
  await fresh.getByRole('button',{name:'Maintenance',exact:false}).click();
  await fresh.locator('#verify-install').click();
  await fresh.locator('#confirm-action').click();
  await fresh.waitForFunction(async()=>{
    const status=await (await fetch('/api/status')).json();
    return status.job.stage==='ready' && status.logs.some(line=>line.includes('Existing server files found'));
  });
  const repeated = await (await requestContext.get('http://127.0.0.1:8091/api/status')).json();
  assert.equal(repeated.config.server_name,'Fresh CS2');
  assert.equal(repeated.job.installed_build,'12345');
  await fresh.locator('#logout').click();
  await fresh.getByRole('heading',{name:'Welcome back'}).waitFor();
  await fresh.locator('#auth-form [name="username"]').fill('first-owner');
  await fresh.locator('#auth-form [name="password"]').fill('first-panel-password');
  await fresh.locator('#auth-submit').click();
  await fresh.locator('#logout').waitFor({state:'visible'});
  await fresh.getByRole('button',{name:'Dashboard',exact:false}).click();
  await fresh.locator('#dashboard').waitFor({state:'visible'});
  assert.deepEqual(errors,[]);
  await browser.close();console.log('Browser authentication, layout, user/admin/ban actions, first installation and verified reinstallation passed.');
})().catch(error=>{console.error(error);process.exit(1)});
